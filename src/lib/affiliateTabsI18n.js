/**
 * Split a translated template around `{var}` placeholders and drop the given
 * nodes in (e.g. a <strong> amount inside a sentence), so the whole sentence
 * stays in the dictionary in both languages. Pure: returns an array of strings
 * and the caller's nodes (give those nodes a `key`).
 *   fillParts("gagnez {amount} par vente", { amount: <strong key="a">5 DH</strong> })
 */
export function fillParts(template, parts) {
  const out = [];
  const re = /\{(\w+)\}/g;
  let last = 0;
  let m;
  const s = String(template ?? "");
  while ((m = re.exec(s))) {
    if (m.index > last) out.push(s.slice(last, m.index));
    out.push(parts && parts[m[1]] !== undefined ? parts[m[1]] : m[0]);
    last = m.index + m[0].length;
  }
  if (last < s.length) out.push(s.slice(last));
  return out;
}
