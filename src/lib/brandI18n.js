export const BRAND_TEXT = Object.freeze({ fr: Object.freeze(fr), ar: Object.freeze(ar) });

/** Supported languages; anything else falls back to French. */
export const brandLang = (lang) => (lang === 'ar' ? 'ar' : 'fr');
export const brandDir = (lang) => (brandLang(lang) === 'ar' ? 'rtl' : 'ltr');

/** Translator for one language: t('starts_on', { date }). Missing key → French → key. */
export function brandT(lang) {
  const dict = BRAND_TEXT[brandLang(lang)];
  return (key, vars) => {
    const raw = dict[key] ?? BRAND_TEXT.fr[key] ?? key;
    return vars ? raw.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m)) : raw;
  };
}
